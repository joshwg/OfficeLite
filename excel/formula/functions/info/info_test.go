package info

import (
	"testing"

	f "officelite/excel/formula"
	"officelite/excel/formula/functions/internal/ftest"
)

func TestInfo(t *testing.T) {
	r := f.NewRegistry()
	Register(r)
	ftest.Run(t, r, func(ctx *f.TestContext) {
		ctx.SetRange("A1", [][]any{
			{1, "=A1*2"},
			{"text", "=\"\""},
			{true, nil},
			{f.ErrNA, "=1/0"},
			{f.ErrDiv0, 4},
			{nil, 7},
		})
		ctx.Set("Sheet2!C3", 5)
		ctx.Set("D1", "Sheet2")
		ctx.Sheets = append(ctx.Sheets, "My Data")
	}, []ftest.Case{
		// ISBLANK: only truly empty cells.
		{"=ISBLANK(A6)", true},
		{"=ISBLANK(B2)", false}, // formula returning ""
		{"=ISBLANK(\"\")", false},
		{"=ISBLANK(0)", false},
		{"=ISBLANK(A1:A6)", ftest.Arr{{false}, {false}, {false}, {false}, {false}, {true}}},
		{"=LAMBDA(x,ISBLANK(x))()", true},

		{"=ISERR(A4)", false},
		{"=ISERR(A5)", true},
		{"=ISERR(#REF!)", true},
		{"=ISERR(1)", false},
		{"=ISERROR(A4)", true},
		{"=ISERROR(B4)", true},
		{"=ISERROR(\"#N/A\")", false},
		{"=ISERROR({1,#N/A,#VALUE!})", ftest.Arr{{false, true, true}}},
		{"=ISNA(A4)", true},
		{"=ISNA(A5)", false},
		{"=ISNA(NA())", true},
		{"=ISNA({1,#N/A})", ftest.Arr{{false, true}}},

		{"=ISEVEN(2)", true},
		{"=ISEVEN(-1)", false},
		{"=ISEVEN(2.5)", true},
		{"=ISEVEN(5)", false},
		{"=ISEVEN(A6)", true},
		{"=ISEVEN(0)", true},
		{"=ISEVEN(\"4\")", true},
		{"=ISEVEN(TRUE)", f.ErrValue},
		{"=ISEVEN(\"x\")", f.ErrValue},
		{"=ISEVEN(#N/A)", f.ErrNA},
		{"=ISODD(-1)", true},
		{"=ISODD(2)", false},
		{"=ISODD(3.9)", true},
		{"=ISODD(-3.9)", true},
		{"=ISODD({1,2,3})", ftest.Arr{{true, false, true}}},

		{"=ISLOGICAL(A3)", true},
		{"=ISLOGICAL(1)", false},
		{"=ISLOGICAL(\"TRUE\")", false},
		{"=ISNUMBER(A1)", true},
		{"=ISNUMBER(\"1\")", false},
		{"=ISNUMBER(A6)", false},
		{"=ISNUMBER(A4)", false},
		{"=ISNUMBER(A1:B2)", ftest.Arr{{true, true}, {false, false}}},
		{"=ISTEXT(A2)", true},
		{"=ISTEXT(B2)", true},
		{"=ISTEXT(A1)", false},
		{"=ISTEXT(A6)", false},
		{"=ISNONTEXT(A2)", false},
		{"=ISNONTEXT(A6)", true},
		{"=ISNONTEXT(A4)", true},
		{"=ISNONTEXT(A1)", true},

		{"=LAMBDA(a,b,ISOMITTED(b))(1)", true},
		{"=LAMBDA(a,b,ISOMITTED(b))(1,2)", false},
		{"=ISOMITTED(1)", false},

		{"=ISREF(A1)", true},
		{"=ISREF(A1:B3)", true},
		{"=ISREF(Sheet2!C3)", true},
		{"=ISREF(1)", false},
		{"=ISREF(\"A1\")", false},
		{"=ISREF({1,2})", false},
		{"=ISREF(#REF!)", false},
		{"=ISREF(NoSuchSheet!A1)", false},

		{"=ISFORMULA(B1)", true},
		{"=ISFORMULA(A1)", false},
		{"=ISFORMULA(Z99)", false},
		{"=ISFORMULA(A1:B2)", ftest.Arr{{false, true}, {false, true}}},
		{"=ISFORMULA(1)", f.ErrValue},
		{"=ISFORMULA(#REF!)", f.ErrRef},

		{"=N(7)", 7.0},
		{"=N(A1)", 1.0},
		{"=N(A3)", 1.0},
		{"=N(FALSE)", 0.0},
		{"=N(A2)", 0.0},
		{"=N(\"7\")", 0.0},
		{"=N(A6)", 0.0},
		{"=N(A5)", f.ErrDiv0},
		{"=N({1,\"a\",TRUE})", ftest.Arr{{1.0, 0.0, 1.0}}},
		{"=NA()", f.ErrNA},

		{"=TYPE(A1)", 1.0},
		{"=TYPE(A6)", 1.0},
		{"=TYPE(\"Smith\")", 2.0},
		{"=TYPE(A2)", 2.0},
		{"=TYPE(TRUE)", 4.0},
		{"=TYPE(1/0)", 16.0},
		{"=TYPE(A4)", 16.0},
		{"=TYPE({1,2;3,4})", 64.0},
		{"=TYPE(A1:A3)", 64.0},
		{"=TYPE(2+A1)", 1.0},
		{"=TYPE(\"MR. \"&A2)", 2.0},

		{"=ERROR.TYPE(#NULL!)", 1.0},
		{"=ERROR.TYPE(A5)", 2.0},
		{"=ERROR.TYPE(#VALUE!)", 3.0},
		{"=ERROR.TYPE(#REF!)", 4.0},
		{"=ERROR.TYPE(#NAME?)", 5.0},
		{"=ERROR.TYPE(#NUM!)", 6.0},
		{"=ERROR.TYPE(A4)", 7.0},
		{"=ERROR.TYPE(#GETTING_DATA)", 8.0},
		{"=ERROR.TYPE(#SPILL!)", 9.0},
		{"=ERROR.TYPE(#CALC!)", 14.0},
		{"=ERROR.TYPE(1)", f.ErrNA},
		{"=ERROR.TYPE(A6)", f.ErrNA},
		{"=ERROR.TYPE({1,#N/A})", ftest.Arr{{f.ErrNA, 7.0}}},

		{"=SHEET()", 1.0},
		{"=SHEET(A1)", 1.0},
		{"=SHEET(Sheet2!C3)", 2.0},
		{"=SHEET(\"Sheet2\")", 2.0},
		{"=SHEET(\"sheet2\")", 2.0},
		{"=SHEET(\"My Data\")", 3.0},
		{"=SHEET(D1)", 1.0}, // the reference, not the text in it
		{"=SHEET(\"Nope\")", f.ErrNA},
		{"=SHEET(#REF!)", f.ErrRef},
		{"=SHEETS()", 3.0},
		{"=SHEETS(Sheet2!A1:B5)", 1.0},
		{"=SHEETS(1)", f.ErrRef},

		{"=CELL(\"address\",B3)", "$B$3"},
		{"=CELL(\"address\",B3:C9)", "$B$3"},
		{"=CELL(\"Address\",AB12)", "$AB$12"},
		{"=CELL(\"address\",Sheet2!C3)", "Sheet2!$C$3"},
		{"=CELL(\"address\",'My Data'!C3)", "'My Data'!$C$3"},
		{"=CELL(\"address\")", "$A$1000"},
		{"=CELL(\"col\",D7)", 4.0},
		{"=CELL(\"row\",D7)", 7.0},
		{"=CELL(\"row\",A3:A9)", 3.0},
		{"=CELL(\"row\")", 1000.0},
		{"=CELL(\"contents\",A2)", "text"},
		{"=CELL(\"contents\",B1)", 2.0},
		{"=CELL(\"contents\",Sheet2!C3)", 5.0},
		{"=CELL(\"type\",A6)", "b"},
		{"=CELL(\"type\",A2)", "l"},
		{"=CELL(\"type\",B2)", "l"},
		{"=CELL(\"type\",A1)", "v"},
		{"=CELL(\"type\",A4)", "v"},
		{"=CELL(\"filename\",A1)", ""},
		{"=CELL(\"format\",A1)", "G"},
		{"=CELL(\"prefix\",A2)", "'"},
		{"=CELL(\"prefix\",A1)", ""},
		{"=CELL(\"protect\",A1)", 1.0},
		{"=CELL(\"color\",A1)", 0.0},
		{"=CELL(\"parentheses\",A1)", 0.0},
		{"=CELL(\"width\",A1)", ftest.Arr{{8.0, true}}},
		{"=CELL(\"bogus\",A1)", f.ErrValue},
		{"=CELL(\"type\",5)", f.ErrValue},
		{"=CELL({\"row\",\"col\"},C5)", ftest.Arr{{5.0, 3.0}}},

		{"=INFO(\"system\")", "pcdos"},
		{"=INFO(\"recalc\")", "Automatic"},
		{"=INFO(\"origin\")", "$A:$A$1"},
		{"=INFO(\"numfile\")", 3.0},
		{"=INFO(\"release\")", "16.0"},
		{"=INFO(\"osversion\")", "Windows (64-bit) NT 10.00"},
		{"=INFO(\"directory\")", ""},
		{"=INFO(\"memavail\")", f.ErrNA},
		{"=INFO(\"x\")", f.ErrValue},

		{"=STOCKHISTORY(\"MSFT\",1/0)", f.ErrDiv0},
		{"=STOCKHISTORY(\"MSFT\",43831)", f.ErrConnect},
		{"=STOCKHISTORY(\"MSFT\",43831,43900,0,1,0,1,2)", f.ErrConnect},
	})
}
