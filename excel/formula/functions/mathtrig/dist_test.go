// Extreme parameters: tails, tiny and huge shapes, large counts.
func TestDistributionsExtreme(t *testing.T) {
	ftest.Run(t, registry(), nil, []ftest.Case{
		{"=BETA.INV(0.5,0.01,0.01)", 0.5},
		{"=BETA.INV(1E-10,1000,2)", 0.9740225210945375},
		{"=BETA.INV(0.3,0.5,3)", 0.02652228581049731},
		{"=GAMMA.INV(0.5,0.001,1)", 5.244206408274974e-302},
		{"=GAMMA.INV(0.999,500,3)", 1715.8756389295186},
		{"=CHISQ.INV(0.999999,1000000)", 1006736.7596362823},
		{"=T.INV(0.9999999,1)", 3183098.8635132452},
		{"=T.INV(0.3,3)", -0.5843897274398188},
		{"=F.INV(0.5,1,1000000)", 0.45493675407152634},
		{"=F.INV.RT(1E-9,3,7)", 1104.7160804248183}, // checked forward with mpmath; SciPy's isf is off by 1e-8
		{"=BINOM.INV(1000000,0.5,0.5)", 500000.0},
		{"=POISSON.DIST(1000,1000,TRUE)", 0.508409367168506},
		{"=POISSON.DIST(1000,1000,FALSE)", 0.01261461134870819},
		{"=T.DIST(2,100000,TRUE)", 0.9772485182712467},
		{"=CHISQ.DIST.RT(1,200)", 1.0},
		{"=HYPGEOM.DIST(500,2000,5000,10000,TRUE)", 4.563431407537492e-143},
		{"=NEGBINOM.DIST(2000,1000,0.3,TRUE)", 4.289056424874652e-05},
		{"=GAMMA.DIST(0.001,0.5,1,TRUE)", 0.035670591729679894},
	})
}
