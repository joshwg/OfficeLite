package mathtrig

import (
	"testing"

	f "officelite/excel/formula"
	"officelite/excel/formula/functions/internal/ftest"
)

func TestRounding(t *testing.T) {
	ftest.Run(t, registry(), nil, []ftest.Case{
		{"=ROUND(2.15,1)", 2.2},
		{"=ROUND(2.149,1)", 2.1},
		{"=ROUND(-1.475,2)", -1.48},
		{"=ROUND(21.5,-1)", 20},
		{"=ROUND(626.3,-3)", 1000},
		{"=ROUND(1.98,-1)", 0},
		{"=ROUND(-50.55,-2)", -100},
		{"=ROUND(2.5,0)", 3},
		{"=ROUND(-2.5,0)", -3},
		{"=ROUND(0.5,0)", 1},
		{"=ROUND(1.005,2)", 1.01},
		{"=ROUND(0.285,2)", 0.29},
		{"=ROUND(1.0049999,2)", 1},
		{"=ROUND(1234.5678,-2)", 1200},
		{"=ROUND(1234.5678,2)", 1234.57},
		{"=ROUND(4.35,1)", 4.4},
		{"=ROUND(5,)", 5},
		{"=ROUND(1.5,2.9)", 1.5},
		{"=ROUND(0.1+0.2,20)", 0.3},
		{"=ROUND(5E-300,2)", 0},
		{"=ROUND(4,-1)", 0},
		{"=ROUND(5,-1)", 10},
		{"=ROUND(\"x\",1)", f.ErrValue},
		{"=ROUND({1.25,-1.25},1)", ftest.Arr{{1.3, -1.3}}},
		{"=ROUNDUP(3.2,0)", 4},
		{"=ROUNDUP(76.9,0)", 77},
		{"=ROUNDUP(3.14159,3)", 3.142},
		{"=ROUNDUP(-3.14159,1)", -3.2},
		{"=ROUNDUP(31415.92654,-2)", 31500},
		{"=ROUNDUP(3,0)", 3},
		{"=ROUNDUP(0.0001,-2)", 100},
		{"=ROUNDUP(0.1+0.2,1)", 0.3},
		{"=ROUNDDOWN(3.2,0)", 3},
		{"=ROUNDDOWN(76.9,0)", 76},
		{"=ROUNDDOWN(3.14159,3)", 3.141},
		{"=ROUNDDOWN(-3.14159,1)", -3.1},
		{"=ROUNDDOWN(31415.92654,-2)", 31400},
		{"=TRUNC(8.9)", 8},
		{"=TRUNC(-8.9)", -8},
		{"=TRUNC(0.45)", 0},
		{"=TRUNC(3.14159,2)", 3.14},
		{"=TRUNC(1234,-2)", 1200},
		{"=INT(8.9)", 8},
		{"=INT(-8.9)", -9},
		{"=INT(\"5.5\")", 5},
		{"=EVEN(1.5)", 2},
		{"=EVEN(3)", 4},
		{"=EVEN(2)", 2},
		{"=EVEN(-1)", -2},
		{"=EVEN(0)", 0},
		{"=ODD(1.5)", 3},
		{"=ODD(3)", 3},
		{"=ODD(2)", 3},
		{"=ODD(-1)", -1},
		{"=ODD(-2)", -3},
		{"=ODD(0)", 1},
		{"=MROUND(10,3)", 9},
		{"=MROUND(-10,-3)", -9},
		{"=MROUND(1.3,0.2)", 1.4},
		{"=MROUND(5,-2)", f.ErrNum},
		{"=MROUND(5,0)", 0},
		{"=MROUND(7.5,5)", 10},
		{"=MROUND(-7.5,-5)", -10},
		{"=CEILING(2.5,1)", 3},
		{"=CEILING(-2.5,-2)", -4},
		{"=CEILING(-2.5,2)", -2},
		{"=CEILING(1.5,0.1)", 1.5},
		{"=CEILING(0.234,0.01)", 0.24},
		{"=CEILING(0.3,0.1)", 0.3},
		{"=CEILING(2.5,0)", 0},
		{"=CEILING(2.5,-2)", f.ErrNum},
		{"=FLOOR(3.7,2)", 2},
		{"=FLOOR(-2.5,-2)", -2},
		{"=FLOOR(-2.5,2)", -4},
		{"=FLOOR(2.5,-2)", f.ErrNum},
		{"=FLOOR(1.58,0.1)", 1.5},
		{"=FLOOR(0.234,0.01)", 0.23},
		{"=FLOOR(0.7,0.1)", 0.7},
		{"=FLOOR(1,0)", f.ErrDiv0},
		{"=CEILING.MATH(24.3,5)", 25},
		{"=CEILING.MATH(6.7)", 7},
		{"=CEILING.MATH(-8.1,2)", -8},
		{"=CEILING.MATH(-5.5,2,-1)", -6},
		{"=CEILING.MATH(-5.5,-2)", -4},
		{"=CEILING.MATH(5,0)", 0},
		{"=FLOOR.MATH(24.3,5)", 20},
		{"=FLOOR.MATH(6.7)", 6},
		{"=FLOOR.MATH(-8.1,2)", -10},
		{"=FLOOR.MATH(-5.5,2,-1)", -4},
		{"=FLOOR.MATH(-5.5,2,0)", -6},
		{"=CEILING.PRECISE(4.3)", 5},
		{"=CEILING.PRECISE(-4.3)", -4},
		{"=CEILING.PRECISE(4.3,2)", 6},
		{"=CEILING.PRECISE(4.3,-2)", 6},
		{"=CEILING.PRECISE(-4.3,2)", -4},
		{"=CEILING.PRECISE(-4.3,-2)", -4},
		{"=CEILING.PRECISE(4.3,0)", 0},
		{"=ISO.CEILING(4.3)", 5},
		{"=ISO.CEILING(-4.3,-2)", -4},
		{"=FLOOR.PRECISE(-3.2,-1)", -4},
		{"=FLOOR.PRECISE(3.2,1)", 3},
		{"=FLOOR.PRECISE(-3.2,1)", -4},
		{"=FLOOR.PRECISE(3.2,-1)", 3},
		{"=FLOOR.PRECISE(3.2,0)", 0},
		{"=FLOOR.PRECISE(3.2)", 3},
	})
}
